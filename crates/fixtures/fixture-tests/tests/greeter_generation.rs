#[test]
fn resolved_hello_import_runs_through_the_typed_greeter_surface() {
    let greeter_id = BoxId::new("greeter").unwrap();
    let hello_id = BoxId::new("hello").unwrap();
    let greeter_descriptor = greeter_generated::implementation_descriptor();
    let capability = greeter_descriptor.contract().capabilities()[0].id().clone();
    let transport = Arc::new(StubTransport::new());
    let mut builder = CompositionBuilder::new();

    builder.add_box(hello_generated::implementation_descriptor(), |imports| {
        hello_generated::factory(HelloService, imports)
    });
    builder.add_box(greeter_descriptor, |imports| {
        let typed = greeter_generated::typed_imports(&imports);
        greeter_generated::factory(GreeterService::new(typed.hello), imports)
    });
    builder.resolve_import(
        greeter_id.clone(),
        hello_id.clone(),
        ImportTarget::local(hello_id),
    );
    builder.expose(
        greeter_id,
        capability,
        transport.clone(),
        ExposureLevel::External,
    );

    let composition = builder.start().expect("resolved composition starts");
    let runtime = transport.runtime().expect("stub transport started");
    let [exposure] = runtime.exposures() else {
        panic!("greeter must have exactly one typed exposure")
    };
    let greeter =
        greeter_contract::GreeterHandle::from_erased(Arc::new(ExposureTarget(exposure.clone())));
    let greeting = run(greeter.greet_loudly(context(), "Ada".to_owned()))
        .expect("greeter call succeeds through resolved Hello import");
    assert_eq!(greeting, "HELLO, ADA!");
    drop(composition);
}
